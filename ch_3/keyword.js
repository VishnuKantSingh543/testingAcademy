// KEYWORDS-reserved words that have special meaning
// cannot be used as identifiers


// Variable Declaration Keywords
// var, let, const
var x = 1;  
// declares a variable (function-scoped-inside a function)
let y = 2;   
// declares a variable (block-scoped-inside {})
const z = 3;   
// declares a constant (block-scoped, cannot be reassigned)


// Control Flow Keywords
// if, else, switch, case, break, default

// Loop Keywords
// for, while, do, continue, break

// Function Keywords
// function, return, typeof, yield

// Object & Class Keywords
// new, this, class, extends, super, instanceof

// Error Handling Keywords
// try, catch, finally, throw

// Other Important Keywords
// in, of, delete, void, with, debugger
